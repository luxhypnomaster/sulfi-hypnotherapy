#!/usr/bin/env python3
"""Read-only integration audit. Does not build/sign/install/dispatch/deploy.

Pins are review inputs, never regenerated by this script. A changed or added
runtime file requires a new, independently reviewed scope, not a silent re-pin.
"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[2]
RUNTIME = ("lib/", "android/", "third_party/", "server/", ".github/")
DEPENDENCIES = {
    "task21": "40b7c59e67921f456c3c5a4e943bd40f7232f336",
    "task22_code": "a5a4c771ab3f9fc9030d46fd6bb41a6a11ea1dde",
    "task23_code": "5fae671c9829c021151e3c9e6ed0467692a7867a",
    "task24_code": "d04170271e9e9f3d9d10d28fdb4a49cf0494a1e0",
    "pr56": "d0a6d9a6daaeca215992e0b771a2332502ecee41",
}


def check_pins(root, pins):
    failures = []
    for name, expected in pins.items():
        relative = Path(name)
        if relative.is_absolute() or ".." in relative.parts:
            raise ValueError("invalid review pin path")
        path = root / relative
        if any(p.is_symlink() for p in [path, *path.parents] if p != root.parent):
            failures.append({"path": name, "reason": "symlink"})
        elif not path.is_file():
            failures.append({"path": name, "reason": "missing"})
        elif hashlib.sha256(path.read_bytes()).hexdigest() != expected:
            failures.append({"path": name, "reason": "hash_mismatch"})
    return failures


def audit(root=ROOT):
    def git(*args):
        return subprocess.check_output(["git", *args], cwd=root, text=True).strip()

    protected = json.loads((root / "reports/task25/PROTECTED_25.json").read_text())
    native = json.loads((root / "scripts/task23/native_source_pins.json").read_text())
    drift = check_pins(root, protected["files"])
    native_drift = check_pins(root, native["files"])
    all_paths = git("ls-files", "--cached", "--others", "--exclude-standard").splitlines()
    additions = sorted(p for p in set(all_paths) if p.startswith(RUNTIME) and p not in protected["files"])
    ancestry = {}
    for name, sha in DEPENDENCIES.items():
        ancestry[name] = subprocess.run(
            ["git", "merge-base", "--is-ancestor", sha, "HEAD"], cwd=root,
            stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
        ).returncode == 0
    passed = not drift and not native_drift and not additions and all(ancestry.values())
    return {
        "status": "PASS_SOURCE" if passed else "BLOCKED_SOURCE",
        "sourceSHA": git("rev-parse", "HEAD"),
        "basePR56": protected["baseSHA"],
        "runtimeFilesChecked": len(protected["files"]),
        "nativePinsChecked": len(native["files"]),
        "drift": drift, "nativeDrift": native_drift, "unexpectedRuntimeFiles": additions,
        "dependencyAncestry": ancestry,
        "nativeAPK": "BLOCKED_NOT_EXECUTED_BY_THIS_READ_ONLY_TOOL",
        "ownerDevice": "NOT_RUN", "serverProduction": "NOT_RUN",
        "experimentalFlags": "unchanged reviewed source; default OFF",
    }


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.parse_args()  # No build/execute/signing options, no credentials accepted.
    result = audit()
    print(json.dumps(result, indent=2))
    raise SystemExit(0 if result["status"] == "PASS_SOURCE" else 1)


if __name__ == "__main__":
    main()
